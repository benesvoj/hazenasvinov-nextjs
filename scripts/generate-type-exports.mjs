import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Get current directory for ES modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function generateTypeExports(dir, basePath = '') {
  const files = fs.readdirSync(dir);
  const exports = [];
  const seenExports = new Set();

  files.forEach(file => {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);

    if (stat.isDirectory()) {
      // Skip certain directories
      if (file === 'node_modules' || file === '.git' || file === 'dist' || file === 'build') {
        return;
      }

      // Recursively process subdirectories
      const subExports = generateTypeExports(fullPath, path.posix.join(basePath, file));
      exports.push(...subExports);
    } else if (file.endsWith('.ts') && !file.startsWith('index') && file !== 'README.md') {
      // Generate export statement
      const relativePath = path.posix.join(basePath, file.replace('.ts', ''));
      const exportPath = `./${relativePath}`;

      // Check for potential conflicts and handle them
      if (file === 'types.ts') {
        // Handle the main types.ts file specially
        exports.push(`export * from '${exportPath}';`);
      } else if (file === 'README.md' || file.endsWith('.d.ts')) {
        // Skip README files and TypeScript declaration files
        return;
      } else {
        // Handle all other files - simple export for now
        // This will work with the current flat structure
        exports.push(`export * from '${exportPath}';`);
      }
    }
  });

  return exports;
}

// Generate and write index.ts
const typesDir = path.join(__dirname, '..', 'src', 'types');
const exports = generateTypeExports(typesDir);
const outputPath = path.join(typesDir, 'index.ts');

// Create header comment
const header = `// Auto-generated file - do not edit manually
// Generated by: scripts/generate-type-exports.mjs

`;

// Write the file
fs.writeFileSync(outputPath, header + exports.join('\n'));
console.log(`✅ Generated ${exports.length} type exports in ${outputPath}`);
